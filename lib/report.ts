import type {
  AnalysisResult,
  RiskLevel,
  TrackerCategory,
  TrackerReport,
} from "./types";

const RISK_LABEL: Record<RiskLevel, string> = {
  low: "Lower concern",
  medium: "Moderate concern",
  high: "Higher concern",
};

const TRACKER_LABEL: Record<TrackerCategory, string> = {
  essential: "Essential",
  analytics: "Analytics",
  advertising: "Advertising",
  functional: "Functional",
  social: "Social",
  unknown: "Unclassified",
};

function hostOf(url: string): string {
  try {
    return new URL(url).hostname.replace(/^www\./, "");
  } catch {
    return "site";
  }
}

function bullets(items: string[], empty: string): string {
  if (!items.length) return `- ${empty}`;
  return items.map((item) => `- ${item}`).join("\n");
}

function paragraphs(text: string): string {
  return text
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .filter(Boolean)
    .join("\n\n");
}

export function reportFileName(result: AnalysisResult, ext: string): string {
  const host = hostOf(result.policyUrl || result.inputUrl);
  const date = (result.analyzedAt || new Date().toISOString()).slice(0, 10);
  const slug = host.replace(/[^a-z0-9.-]/gi, "-");
  return `policybrief-${slug}-${date}.${ext}`;
}

function trackerSection(trackers: TrackerReport): string {
  const lines: string[] = ["## Cookies & trackers (detected)", ""];

  lines.push(
    `${trackers.counts.cookies} cookie(s) seen in response headers (${trackers.counts.thirdPartyCookies} third-party); ${trackers.technologies.length} tracking technology/ies detected.`,
  );
  lines.push("");

  lines.push("### Cookies set by the site", "");
  if (trackers.cookies.length) {
    for (const cookie of trackers.cookies) {
      const attrs = [
        cookie.session ? "Session" : "Persistent",
        cookie.secure ? "Secure" : null,
        cookie.httpOnly ? "HttpOnly" : null,
        cookie.sameSite ? `SameSite=${cookie.sameSite}` : null,
        cookie.domain,
      ]
        .filter(Boolean)
        .join(" · ");
      const vendor = cookie.vendor ? ` · ${cookie.vendor}` : "";
      lines.push(
        `- \`${cookie.name}\` — ${TRACKER_LABEL[cookie.category]}${vendor} · ${attrs}`,
      );
    }
  } else {
    lines.push("- None found in the response headers of the pages scanned.");
  }
  lines.push("");

  lines.push("### Tracking technologies", "");
  if (trackers.technologies.length) {
    for (const tech of trackers.technologies) {
      lines.push(
        `- **${tech.vendor}** — ${TRACKER_LABEL[tech.category]} — found via ${tech.sources.join(", ")}`,
      );
    }
  } else {
    lines.push("- None detected in the page HTML.");
  }

  if (trackers.notes.length) {
    lines.push("", "### Detection notes", "");
    for (const note of trackers.notes) lines.push(`- ${note}`);
  }

  return lines.join("\n");
}

export function buildMarkdownReport(result: AnalysisResult): string {
  const site = hostOf(result.inputUrl);
  let when = result.analyzedAt;
  try {
    when = new Date(result.analyzedAt).toLocaleString();
  } catch {
    // keep raw ISO string
  }

  return `# Privacy brief — ${site}

- **Site:** ${result.inputUrl}
- **Privacy policy:** ${result.policyUrl}
- **Analyzed:** ${when}

## Summary

${paragraphs(result.summary)}

## Data collected

${bullets(result.dataCollected, "No clear data-collection categories were identified.")}

## Sharing

${bullets(result.sharing, "Sharing practices were not clearly described.")}

## Your rights

${bullets(result.rights, "User rights were not clearly described.")}

## Cookies & tracking

${result.cookies}

## Risks

**${RISK_LABEL[result.risks.level]} — ${result.risks.score}/10**

${result.risks.notes}

**Flags**

${bullets(result.risks.flags, "No specific red flags were called out.")}

${trackerSection(result.trackers)}

---

_Generated by PolicyBrief from the published privacy policy using an AI model; verify against the original policy before relying on it._
`;
}

export function buildJsonReport(result: AnalysisResult): string {
  return `${JSON.stringify(
    {
      generator: "PolicyBrief",
      version: 1,
      exportedAt: new Date().toISOString(),
      result,
    },
    null,
    2,
  )}\n`;
}
